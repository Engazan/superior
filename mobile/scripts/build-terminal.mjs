import { build } from 'esbuild';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
const result = await build({
  entryPoints: ['src/terminal/document.ts'],
  bundle: true,
  write: false,
  minify: true,
  format: 'iife',
  platform: 'browser',
});
const css = await readFile('node_modules/@xterm/xterm/css/xterm.css', 'utf8');
const html = `<!doctype html><html><head><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=3"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; connect-src 'none'; img-src data:; font-src 'none'"><style>${css}html,body{margin:0;background:#0f131a;height:100%;}#terminal{min-width:max-content;height:100%;padding:8px;box-sizing:border-box;}</style></head><body><div id="terminal"></div><script>${result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script')}</script></body></html>`;
await mkdir('src/generated', { recursive: true });
await writeFile(
  'src/generated/terminal-document.ts',
  `// Generated by scripts/build-terminal.mjs.\nexport default ${JSON.stringify(html)};\n`,
);
